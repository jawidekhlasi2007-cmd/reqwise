export const UI_STRINGS: Record<UiLanguage, UiStrings> = { en, ru };

/** Picks a localized message for an error code, falling back to the server's own text. */
export function errorMessage(t: UiStrings, code: string | undefined, fallback?: string): string {
  if (code && t.errors[code]) return t.errors[code];
  return fallback || t.errors.generic;
}
